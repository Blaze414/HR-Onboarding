// A permission nobody checks is a lie: the role editor offers it, an
// administrator ticks it, and nothing changes. This scans the source for every
// capability and reports where each one is actually enforced — failing if any
// key is decoration.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { ALL_CAPABILITIES } from '../../packages/shared/src/capabilities.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** Where a capability may be enforced, and what counts as enforcement there. */
const AREAS = [
  { name: 'database', dirs: ['supabase/migrations'], exts: ['.sql'] },
  { name: 'server', dirs: ['apps/desktop/src/lib', 'apps/desktop/src/app', 'apps/desktop/src/middleware.ts'], exts: ['.ts', '.tsx'] },
  { name: 'desktop UI', dirs: ['apps/desktop/src/components'], exts: ['.ts', '.tsx'] },
  { name: 'mobile', dirs: ['apps/mobile/app', 'apps/mobile/src'], exts: ['.ts', '.tsx'] },
];

// Files that only *define* or *grant* capabilities. A mention here is a
// declaration, never enforcement, so they are excluded from the evidence.
const DECLARATION_ONLY = [
  'packages/shared/src/capabilities.ts',
  'supabase/seed.sql',
];

function walk(target) {
  const full = path.join(root, target);
  let stat;
  try { stat = statSync(full); } catch { return []; }
  if (stat.isFile()) return [full];
  return readdirSync(full, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) return [];
    return walk(path.join(target, entry.name));
  });
}

const corpus = AREAS.map((area) => ({
  name: area.name,
  files: area.dirs
    .flatMap(walk)
    .filter((file) => area.exts.some((ext) => file.endsWith(ext)))
    .filter((file) => !DECLARATION_ONLY.some((skip) => file.endsWith(skip)))
    .map((file) => ({ file: path.relative(root, file), text: readFileSync(file, 'utf8') })),
}));

// A role's permission array in a migration is a grant, not a check. Only these
// forms actually decide anything.
const enforcementPatterns = (capability) => {
  const key = capability.replace(/[.]/g, '\\.');
  return [
    new RegExp(`requireCapability\\(\\s*'${key}'`),
    new RegExp(`sessionCan\\([^,]+,\\s*'${key}'`),
    new RegExp(`\\bcan\\(\\s*'${key}'`),
    new RegExp(`capabilityState\\(\\s*'${key}'`),
    new RegExp(`has_permission\\(\\s*'${key}'`),
    // Policies are generated by `split_admin_policy(table, name, create, update,
    // delete)`, so the capability appears as an argument rather than inside a
    // has_permission call. Reading only the literal form reported these as
    // stale while the database was in fact enforcing them.
    new RegExp(`split_admin_policy\\([^)]*'${key}'`, 's'),
  ];
};

let bad = 0;
const stale = [];
const report = [];

for (const capability of ALL_CAPABILITIES) {
  const patterns = enforcementPatterns(capability);
  const found = [];
  for (const area of corpus) {
    if (area.files.some(({ text }) => patterns.some((p) => p.test(text)))) found.push(area.name);
  }
  if (found.length === 0) { stale.push(capability); bad++; }
  report.push({ capability, found });
}

const width = Math.max(...report.map((r) => r.capability.length));
for (const { capability, found } of report) {
  console.log(
    `${found.length ? 'ok  ' : 'FAIL'} ${capability.padEnd(width)}  ${found.join(', ') || 'ENFORCED NOWHERE'}`,
  );
}

console.log(`\n${report.length - stale.length}/${report.length} capabilities are enforced somewhere.`);
if (stale.length) console.log(`stale: ${stale.join(', ')}`);

process.exit(bad ? 1 : 0);
